#!/bin/sh
# build.sh builds ghosttyvt.wasm: libghostty-vt, compiled for wasm32, linked
# with tsterm's glue (glue/tsterm.c), and writes version.go to describe it.
# It downloads a pinned Zig and the pinned libghostty-vt source into $CACHE
# (default ~/.cache/tsterm-ghosttyvt).
#
# The outputs are committed, so that building tsterm needs neither Zig nor
# this script; rerun it after changing the glue or the pins.
set -eu

ZIG_VERSION=0.17.1
VT_TAG=vt-1.0.0
OPTIMIZE=${OPTIMIZE:-ReleaseFast}

here=$(cd "$(dirname "$0")" && pwd)
cache=${CACHE:-$HOME/.cache/tsterm-ghosttyvt}
mkdir -p "$cache"

case "$(uname -m)" in
x86_64 | amd64) arch=x86_64 ;;
aarch64 | arm64) arch=aarch64 ;;
*) echo "unsupported architecture $(uname -m)" >&2; exit 1 ;;
esac
case "$(uname -s)" in
Linux) os=linux ;;
Darwin) os=macos ;;
*) echo "unsupported OS $(uname -s)" >&2; exit 1 ;;
esac

zig_dir=$cache/zig-$arch-$os-$ZIG_VERSION
if [ ! -x "$zig_dir/zig" ]; then
	curl -fsSL "https://ziglang.org/download/$ZIG_VERSION/zig-$arch-$os-$ZIG_VERSION.tar.xz" | tar xJ -C "$cache"
fi
zig=$zig_dir/zig

# The tag's tarball unpacks to ghostty-$VT_TAG.
src=$cache/ghostty-$VT_TAG
if [ ! -d "$src" ]; then
	curl -fsSL "https://github.com/ghostty-org/ghostty/archive/refs/tags/$VT_TAG.tar.gz" | tar xz -C "$cache"
fi

(cd "$src" && "$zig" build -Demit-lib-vt -Dtarget=wasm32-freestanding -Doptimize="$OPTIMIZE")

"$zig" cc -target wasm32-freestanding -O2 -nostdlib \
	-I "$src/include" \
	"$here/glue/tsterm.c" "$src/zig-out/lib/libghostty-vt.a" \
	-Wl,--no-entry \
	-Wl,--export=ghostty_wasm_alloc -Wl,--export=ghostty_wasm_free \
	-Wl,-z,stack-size=1048576 \
	-Wl,--strip-debug \
	-o "$here/ghosttyvt.wasm"
chmod 644 "$here/ghosttyvt.wasm"

abi=$(sed -n 's/^#define TSTERM_ABI_VERSION \([0-9]*\)$/\1/p' "$here/glue/tsterm.c")
cat >"$here/version.go" <<GO
// Code generated by build.sh. DO NOT EDIT.

package ghosttyvt

// ABIVersion is the version of the contract between Wasm's glue and its Go
// caller (TSTERM_ABI_VERSION in glue/tsterm.c). Wasm's tsterm_abi_version
// export returns it too.
const ABIVersion = $abi

// LibghosttyTag is the libghostty-vt release tag Wasm was built from.
const LibghosttyTag = "$VT_TAG"

// ZigVersion is the Zig version Wasm was built with.
const ZigVersion = "$ZIG_VERSION"

// Optimize is the Zig optimization mode Wasm was built with.
const Optimize = "$OPTIMIZE"
GO
ls -l "$here/ghosttyvt.wasm"
